#!/usr/bin/env python3
"""Generate the integer decay table (offline, exact big-integer arithmetic).

The pure function forbids floats (risk-function area rule 1). Decay is
2^(-age/half_life); we quantize age into milli-quanta q = age_milli/half_life
and precompute

    TABLE[frac] = round_half_up(1000 * 2^(-frac/1000)),  frac in 0..999

so the runtime computation is pure integer shifts:

    decay_milli(q) = TABLE[q % 1000] >> (q // 1000)

Monotonicity (required by the property suite): TABLE is non-increasing in
frac, and TABLE[999] >= TABLE[0] >> 1 (500 >= 500), so the composite is
non-increasing in q — older evidence never counts more.

This script runs OFFLINE (build time) with exact big-integer fixed-point
arithmetic (64 fractional bits, Newton iteration for 2^(1/1000)). Its output
is reviewed like code and committed; the function never executes float math.
"""
from __future__ import annotations

from pathlib import Path

OUT = Path(__file__).resolve().parent.parent / "areas" / "risk-function" / "riskfn" / "_decay_table.py"
N = 1000  # milli-quanta per half-life
PREC = 64
ONE = 1 << PREC


def base_pow2_1000() -> int:
    """ceil(2^(1/1000) * ONE) — smallest fixed-point x with x^1000 >= 2*ONE^1000."""
    lo, hi = ONE, 2 * ONE
    target = 2 * ONE**1000
    while lo < hi:
        mid = (lo + hi) // 2
        if mid**1000 >= target:
            hi = mid
        else:
            lo = mid + 1
    return lo


BASE = base_pow2_1000()


def pow2_scaled(k: int) -> int:
    """floor(2^(k/1000) * ONE) via binary exponentiation in fixed point."""
    result, b, e = ONE, BASE, k
    while e:
        if e & 1:
            result = (result * b) >> PREC
        b = (b * b) >> PREC
        e >>= 1
    return result


def round_half_up(num: int, den: int) -> int:
    return (2 * num + den) // (2 * den)


def main() -> None:
    table = []
    for frac in range(N):
        # 2^(-frac/1000) = 2^((1000-frac)/1000) / 2
        p = pow2_scaled(N - frac)
        table.append(round_half_up(1000 * p, 2 * ONE))

    assert table[0] == 1000, table[0]
    assert table == sorted(table, reverse=True), "table must be non-increasing"
    assert table[N - 1] >= table[0] >> 1, "boundary monotonicity"

    body = ", ".join(str(v) for v in table)
    OUT.write_text(
        '"""Integer decay table — GENERATED by scripts/gen_decay_table.py.\n\n'
        "TABLE[frac] = round_half_up(1000 * 2^(-frac/1000)), frac in 0..999.\n"
        "Runtime use: decay_milli(q) = TABLE[q % 1000] >> (q // 1000).\n"
        "Do not edit by hand; regenerate with the script (offline, exact).\n"
        '"""\n\n'
        "DECAY_TABLE_MILLI: tuple[int, ...] = (\n    " + body + ",\n)\n\n"
        "assert len(DECAY_TABLE_MILLI) == 1000\n",
        encoding="utf-8",
    )
    print(f"wrote {OUT} ({len(table)} entries)")
    print("sanity: TABLE[0]=%d TABLE[500]=%d TABLE[999]=%d" % (table[0], table[500], table[999]))


if __name__ == "__main__":
    main()
